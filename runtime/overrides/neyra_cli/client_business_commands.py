BUSINESS_COMMAND_NAMES: Final[frozenset[str]] = frozenset(BUSINESS_PROMPTS)


def is_business_command(name: str | None) -> bool:
    return bool(name and name.lower().lstrip("/") in BUSINESS_COMMAND_NAMES)


def build_business_prompt(name: str, user_text: str) -> tuple[str | None, str | None]:
    """Return ``(prompt, error)`` for a business slash command."""
    normalized = name.lower().lstrip("/")
    command = BUSINESS_PROMPTS.get(normalized)
    if command is None:
        return None, "Неизвестная бизнес-команда."
    empty_message, instruction = command
    material = (user_text or "").strip()
    if not material:
        return None, empty_message
    prompt = (
        f"[Бизнес-команда /{normalized}]\n"
        f"{instruction}\n\n"
        "Материал пользователя:\n"
        f"{material}"
    )
    return prompt, None


def telegram_client_menu_commands() -> list[tuple[str, str]]:
    """Return the validated, ordered menu published to Telegram."""
    names = [name for name, _description in CLIENT_TELEGRAM_MENU]
    if len(names) != len(set(names)):
        raise RuntimeError("client Telegram menu contains duplicate commands")
    for name, description in CLIENT_TELEGRAM_MENU:
        if not re.fullmatch(r"[a-z0-9_]{1,32}", name):
            raise RuntimeError(f"invalid Telegram command name: {name}")
        if not description or len(description) > 256:
            raise RuntimeError(f"invalid Telegram command description: {name}")
    return list(CLIENT_TELEGRAM_MENU)


